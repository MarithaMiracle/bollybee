#!/usr/bin/env node
/**
 * Generates supabase/migrations/007_nigeria_lgas.sql from public LGA JSON.
 * Usage: node scripts/generate-lga-migration.mjs
 */
import { writeFileSync } from "fs";

const JSON_URL =
  "https://raw.githubusercontent.com/Tomilola-ng/nigeria-locations-json/main/data/v1-data.json";

function dbStateName(jsonState) {
  if (jsonState === "abuja") return "FCT Abuja";
  return jsonState
    .split(" ")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

function titleCaseLga(name) {
  return name
    .split(" ")
    .map((word) => {
      if (!word) return word;
      // Preserve apostrophes: jama'are → Jama'are
      return word
        .split("'")
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join("'");
    })
    .join(" ");
}

function escapeSql(str) {
  return str.replace(/'/g, "''");
}

const res = await fetch(JSON_URL);
if (!res.ok) throw new Error(`Failed to fetch LGA data: ${res.status}`);
const { locations } = await res.json();

const rows = [];
for (const entry of locations) {
  const stateName = dbStateName(entry.state);
  const seen = new Set();
  for (const raw of entry.localGovt) {
    const lgaName = titleCaseLga(raw.trim());
    const key = lgaName.toLowerCase();
    if (!lgaName || seen.has(key)) continue;
    seen.add(key);
    rows.push({ stateName, lgaName });
  }
}

const values = rows
  .map(
    ({ stateName, lgaName }) =>
      `  ('${escapeSql(stateName)}', '${escapeSql(lgaName)}')`
  )
  .join(",\n");

const sql = `-- All Nigerian LGAs (generated by scripts/generate-lga-migration.mjs)
-- Inserts missing LGAs only; existing seed rows (Lagos, FCT, Rivers) are kept.

INSERT INTO lgas (state_id, name)
SELECT s.id, v.lga_name
FROM (VALUES
${values}
) AS v(state_name, lga_name)
JOIN states s ON s.name = v.state_name
WHERE NOT EXISTS (
  SELECT 1 FROM lgas l
  WHERE l.state_id = s.id AND lower(l.name) = lower(v.lga_name)
);
`;

writeFileSync("supabase/migrations/007_nigeria_lgas.sql", sql);
console.log(`Wrote ${rows.length} LGAs to supabase/migrations/007_nigeria_lgas.sql`);
